import type { Agent, WatchedRepo } from "./types";

/**
 * The script runs inside actions/github-script (Node 20): it diffs the push
 * with the job's GITHUB_TOKEN and posts the change to Wisdom Ops. No checkout,
 * no jq, nothing to install on self-hosted runners.
 * Written as plain strings because it contains JS template literals.
 */
const SCRIPT_LINES = [
  "const p = context.payload;",
  "if (p.deleted) { core.info('Branch deleted; nothing to send.'); return; }",
  "const { owner, repo } = context.repo;",
  "const ZERO = '0000000000000000000000000000000000000000';",
  "const base = !p.before || p.before === ZERO ? p.repository.default_branch : p.before;",
  "let files = [];",
  "try {",
  "  const { data } = await github.rest.repos.compareCommitsWithBasehead({ owner, repo, basehead: base + '...' + p.after });",
  "  files = (data.files || []).slice(0, 1000).map(f => ({",
  "    filename: f.filename, status: f.status, additions: f.additions, deletions: f.deletions,",
  "    patch: f.patch ? f.patch.slice(0, 20000) : undefined,",
  "  }));",
  "} catch (e) { core.warning('compare failed: ' + e.message); }",
  "const commits = (p.commits || []).slice(0, 250).map(c => ({",
  "  sha: c.id, message: c.message || '', author: (c.author && (c.author.username || c.author.name)) || '',",
  "  email: c.author && c.author.email, timestamp: c.timestamp, url: c.url,",
  "}));",
  "const body = {",
  "  agentId: process.env.WISDOM_AGENT_ID, repo: owner + '/' + repo,",
  "  branch: context.ref.replace('refs/heads/', ''), before: p.before || '', after: p.after,",
  "  pusher: p.pusher && p.pusher.name, compareUrl: p.compare, commits, files,",
  "};",
  "const res = await fetch(process.env.WISDOM_URL.replace(/\\/$/, '') + '/api/ingest/github', {",
  "  method: 'POST',",
  "  headers: { 'Content-Type': 'application/json', Authorization: 'Bearer ' + process.env.WISDOM_TOKEN },",
  "  body: JSON.stringify(body),",
  "});",
  "const text = await res.text();",
  "if (!res.ok) core.setFailed('Wisdom Ops ingest failed: ' + res.status + ' ' + text);",
  "else core.info('Wisdom Ops: ' + text);",
];

function yamlList(items: string[], indent: string): string {
  return items.map((i) => `${indent}- '${i.replace(/'/g, "''")}'`).join("\n");
}

export function workflowYaml(agent: Pick<Agent, "_id" | "name">, repo: WatchedRepo, appBaseUrl: string): string {
  const branches = repo.branches.length ? repo.branches : [];
  const includePaths = repo.paths.filter((p) => !p.startsWith("!"));
  const on = [
    "on:",
    "  push:",
    branches.length ? `    branches:\n${yamlList(branches, "      ")}` : "    # all branches; server-side filter applies",
    includePaths.length ? `    paths:\n${yamlList(repo.paths, "      ")}` : "",
    "  workflow_dispatch: {}",
  ]
    .filter(Boolean)
    .join("\n");

  return `# Generated by Wisdom Ops for agent "${agent.name}" — repo ${repo.fullName}
# Save as .github/workflows/wisdom-ops.yml
# Required: repository (or org) secret WISDOM_TOKEN = the agent's ingest token.
# Optional: repository/org variable WISDOM_URL to override the app URL, WISDOM_RUNNER to pick a runner label.
name: Wisdom Ops change notify
${on}
permissions:
  contents: read
concurrency:
  group: wisdom-ops-\${{ github.ref }}
  cancel-in-progress: false
jobs:
  notify:
    runs-on: \${{ vars.WISDOM_RUNNER || 'ubuntu-latest' }}
    timeout-minutes: 5
    steps:
      - name: Send change to Wisdom Ops
        uses: actions/github-script@v7
        env:
          WISDOM_URL: \${{ vars.WISDOM_URL || '${appBaseUrl}' }}
          WISDOM_TOKEN: \${{ secrets.WISDOM_TOKEN }}
          WISDOM_AGENT_ID: '${agent._id}'
        with:
          script: |
${SCRIPT_LINES.map((l) => "            " + l).join("\n")}
`;
}

/** Same script, exported for tests. */
export const ingestScript = SCRIPT_LINES.join("\n");
